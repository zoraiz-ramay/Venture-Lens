"""Regenerates ui/src/scoring/golden-runs.json from real stored evaluations.

The browser re-scores runs under a user's own weighting, which means it re-implements
`core/score.py` and `core/route.py` arithmetic in JavaScript. Fixtures invented by hand would
happily agree with a wrong implementation; these come out of runs the engine actually produced, so
the JS is pinned to observed behaviour rather than to someone's reading of the formula.

Deliberately NOT wired into scripts/gates.sh as a --check step: runs.db grows every time anyone
clicks "Refresh Data", so a freshness gate would go red on ordinary use and teach people to ignore
it. The real pin is tests/test_whatif_weight_parity.py and tests/test_whatif_route_parity.py, which
recompute these entries from today's engine constants.

    py -3 scripts/golden_runs.py
"""
import json
import os
import sqlite3
import sys

_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, _ROOT)

DB = os.path.join(_ROOT, "data", "runs.db")
OUT = os.path.join(_ROOT, "ui", "src", "scoring", "golden-runs.json")

_DIMENSIONS = ("traction", "siemens_fit", "product", "market", "founder", "ecosystem")


def collect():
    # Read-only URI so regenerating fixtures can never mutate the evaluation history.
    con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
    out = []
    for run_id, company, raw in con.execute(
            "SELECT id, company, result_json FROM runs ORDER BY id"):
        try:
            result = json.loads(raw) or {}
        except (TypeError, ValueError):
            continue
        score = result.get("score") or {}
        dims = score.get("dimensions") or {}
        # A run missing a dimension predates the current set; the engine would KeyError on it, so
        # it cannot pin anything.
        if any(k not in dims for k in _DIMENSIONS):
            continue
        routing = result.get("routing") or {}
        out.append({
            "run_id": run_id,
            "company": company,
            "dimensions": {k: dims[k] for k in _DIMENSIONS},
            "data_completeness": score.get("data_completeness"),
            "data_confidence": score.get("data_confidence"),
            "raw_score": score.get("raw_score"),
            "final_score": score.get("final_score"),
            "route_scorecards": score.get("route_scorecards") or {},
            "fit_aligned": bool((result.get("fit") or {}).get("aligned", False)),
            "pillar": routing.get("pillar", ""),
            "secondary": routing.get("secondary") or [],
        })
    return out


def main():
    runs = collect()
    pillars = sorted({r["pillar"] for r in runs})
    payload = {
        "_comment": (
            "Generated by scripts/golden_runs.py from real evaluations in data/runs.db. "
            "Do not edit by hand. Pillars present in this corpus: " + ", ".join(pillars) +
            " -- routes absent here (and any non-empty `secondary`) are covered by synthetic "
            "tests in ui/src/scoring/routing.test.js instead, not by this file."
        ),
        "runs": runs,
    }
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=2)
        fh.write("\n")
    print(f"wrote {os.path.relpath(OUT, _ROOT)} ({len(runs)} runs, pillars: {', '.join(pillars)})")


if __name__ == "__main__":
    main()
